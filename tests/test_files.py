"""Files the printer reads: G-code thumbnails (text) and binary G-code thumbnail blocks."""
import struct
import zlib

import pytest
from PIL import Image

from prusa_workbench import bgcode, gcode, render


def _bg_block(typ, data, params=b"\0\0", comp=0):
    hdr = struct.pack("<HHI", typ, comp, len(data)) + (struct.pack("<I", len(data)) if comp else b"")
    body = hdr + params + data
    return body + struct.pack("<I", zlib.crc32(body) & 0xFFFFFFFF)


def _bgcode_file(path):
    data = (b"GCDE" + struct.pack("<IH", 1, 1)
            + _bg_block(bgcode.FILE_META, b"Producer=test\n")
            + _bg_block(bgcode.PRINTER_META, b"printer_model=MINIIS\n")
            + _bg_block(bgcode.PRINT_META, b"x=1\n")
            + _bg_block(bgcode.SLICER_META, b"y=2\n")
            + _bg_block(bgcode.GCODE, b"G1 X1\n"))
    path.write_bytes(data)
    return data


def _img(w, h):
    return render.encode(Image.new("RGBA", (w, h), (200, 100, 0, 255)), "PNG")


def test_bgcode_thumbnails_go_after_printer_metadata(tmp_path):
    f = tmp_path / "a.bgcode"
    _bgcode_file(f)
    bgcode.add_thumbnails(f, [(16, 16, "QOI", b"qoif-data"), (380, 285, "PNG", _img(380, 285))])
    data = f.read_bytes()
    ck, blocks = bgcode.blocks(data)            # raises if any checksum or size is wrong
    assert [b.type for b in blocks] == [bgcode.FILE_META, bgcode.PRINTER_META, bgcode.THUMBNAIL, bgcode.THUMBNAIL,
                                        bgcode.PRINT_META, bgcode.SLICER_META, bgcode.GCODE]
    fmt, w, h = struct.unpack_from("<HHH", data, blocks[3].start + 8)
    assert (fmt, w, h) == (0, 380, 285)          # PNG


def test_bgcode_replaces_old_thumbnails(tmp_path):
    f = tmp_path / "a.bgcode"
    _bgcode_file(f)
    bgcode.add_thumbnails(f, [(16, 16, "PNG", _img(16, 16))])
    bgcode.add_thumbnails(f, [(32, 32, "PNG", _img(32, 32))])
    _, blocks = bgcode.blocks(f.read_bytes())
    assert sum(b.type == bgcode.THUMBNAIL for b in blocks) == 1


def test_bgcode_rejects_corruption(tmp_path):
    f = tmp_path / "a.bgcode"
    data = bytearray(_bgcode_file(f))
    data[30] ^= 0xFF
    with pytest.raises(bgcode.BgcodeError):
        bgcode.blocks(bytes(data))
    with pytest.raises(bgcode.BgcodeError):
        bgcode.blocks(b"; plain text gcode\n")


def test_text_thumbnails_round_trip(tmp_path):
    f = tmp_path / "a.gcode"
    f.write_text("; generated by PrusaSlicer 2.9.6\n\n; \n\nG1 X1\n; thumbnails = 16x16/QOI, 220x124/QOI, 380x285/PNG\n")
    imgs = [(16, 16, "QOI", render.encode(Image.new("RGBA", (16, 16), (1, 2, 3, 255)), "QOI")),
            (380, 285, "PNG", _img(380, 285))]
    gcode.insert_thumbnails(f, imgs)
    assert gcode.read_thumbnails(f) == imgs
    assert f.read_text().startswith("; generated by PrusaSlicer")
    assert gcode.thumbnail_specs(f) == [(16, 16, "QOI"), (220, 124, "QOI"), (380, 285, "PNG")]


def test_parse_gcode_summary(tmp_path):
    f = tmp_path / "a.gcode"
    f.write_text(";LAYER_CHANGE\n;TYPE:Perimeter\nG1 X1 E1\n;LAYER_CHANGE\n;TYPE:Perimeter\n;TYPE:Solid infill\n"
                 "; objects_info = {\"objects\":[{\"name\":\"pin\",\"polygon\":[]}]}\n"
                 "; filament used [mm] = 1234.5\n; total filament used [g] = 3.7\n"
                 "; estimated printing time (normal mode) = 12m 3s\n; layer_height = 0.15\n"
                 "; print_settings_id = 0.15mm X\n")
    s = gcode.parse_gcode(f)
    assert (s["print_time"], s["filament_g"], s["filament_m"], s["layers"]) == ("12m 3s", 3.7, 1.23, 2)
    assert s["objects"] == ["pin"] and s["feature_types"] == {"Perimeter": 2, "Solid infill": 1}
    assert s["settings"]["layer_height"] == "0.15"
