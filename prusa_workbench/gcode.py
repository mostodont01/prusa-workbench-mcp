"""Read the summary PrusaSlicer writes into its G-code (time, filament, objects, settings used)."""
from __future__ import annotations

import json
import math
from pathlib import Path

# Settings shown in the viewer's info panel (and stored in bed-N.json), in display order.
SETTINGS_KEYS = [
    "printer_settings_id", "print_settings_id", "filament_settings_id",
    "layer_height", "first_layer_height", "perimeters", "top_solid_layers", "bottom_solid_layers",
    "fill_density", "fill_pattern", "support_material", "support_material_auto",
    "support_material_buildplate_only", "support_material_threshold", "brim_width", "skirts",
    "temperature", "first_layer_temperature", "bed_temperature", "filament_type", "nozzle_diameter",
    "bed_shape", "max_print_height", "printer_model",
]


def _float(v: str | None) -> float | None:
    try:
        f = float(v)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return None
    return None if math.isnan(f) else f


def parse_gcode(path: Path) -> dict:
    """Pull the summary and the settings used out of PrusaSlicer's comments."""
    meta: dict[str, str] = {}
    types: dict[str, int] = {}
    layers = 0
    with path.open(encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith(";TYPE:"):
                t = line[6:].strip()
                types[t] = types.get(t, 0) + 1
            elif line.startswith(";LAYER_CHANGE"):
                layers += 1
            elif line.startswith("; ") and " = " in line:
                k, v = line[2:].rstrip("\n").split(" = ", 1)
                meta[k] = v
    filament_mm = _float(meta.get("filament used [mm]"))
    try:
        objects = [o["name"] for o in json.loads(meta.get("objects_info", "{}")).get("objects", [])]
    except (ValueError, AttributeError):
        objects = []
    return {
        "print_time": meta.get("estimated printing time (normal mode)"),
        "filament_g": _float(meta.get("total filament used [g]")),
        "filament_m": round(filament_mm / 1000, 2) if filament_mm is not None else None,
        "layers": layers,
        "feature_types": types,
        "objects": objects,
        "settings": {k: meta[k].strip('"') for k in SETTINGS_KEYS if k in meta},
    }


def thumbnail_specs(path: Path) -> list[tuple[int, int, str]]:
    """The printer profile's `thumbnails` setting from the G-code footer, e.g. [(16, 16, 'QOI'), (380, 285, 'PNG')]."""
    spec = ""
    with path.open(encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("; thumbnails = "):
                spec = line.split(" = ", 1)[1].strip()
    out = []
    for part in filter(None, (p.strip() for p in spec.split(","))):
        try:
            dims, _, fmt = part.partition("/")
            w, h = (int(float(x)) for x in dims.lower().split("x"))
            out.append((w, h, (fmt or "PNG").upper()))
        except ValueError:
            continue
    return out


def insert_thumbnails(path: Path, thumbs: list[tuple[int, int, str, bytes]]) -> None:
    """Put thumbnails into the G-code header the way PrusaSlicer does (base64 in comment blocks).
    Any thumbnails already there are kept; ours go first."""
    import base64
    import shutil

    blocks = []
    for w, h, fmt, data in thumbs:
        tag = "thumbnail" if fmt == "PNG" else f"thumbnail_{fmt}"
        b64 = base64.b64encode(data).decode()
        lines = [f"; {b64[i:i + 78]}" for i in range(0, len(b64), 78)]
        blocks.append("\n".join([f"; {tag} begin {w}x{h} {len(b64)}", *lines, f"; {tag} end", "; "]) + "\n")

    tmp = path.with_suffix(path.suffix + ".tmp")
    with path.open("rb") as src, tmp.open("wb") as dst:
        first = src.readline()          # "; generated by PrusaSlicer ..."
        dst.write(first)
        dst.write(b"\n; \n" + "".join(blocks).encode())
        shutil.copyfileobj(src, dst, 1 << 20)
    tmp.replace(path)


def read_thumbnails(path: Path) -> list[tuple[int, int, str, bytes]]:
    """Thumbnails stored in a text G-code header: [(w, h, 'PNG'|'QOI'|'JPG', image bytes)]."""
    import base64
    import re

    out, cur, buf = [], None, []
    with path.open(encoding="utf-8", errors="replace") as f:
        for n, line in enumerate(f):
            m = re.match(r"^; thumbnail(?:_(\w+))? begin (\d+)x(\d+) \d+", line)
            if m:
                cur, buf = ((m.group(1) or "PNG").upper(), int(m.group(2)), int(m.group(3))), []
            elif cur and re.match(r"^; thumbnail(?:_\w+)? end", line):
                out.append((cur[1], cur[2], cur[0], base64.b64decode("".join(buf))))
                cur = None
            elif cur:
                buf.append(line[1:].strip())
            elif n > 2000 and not cur:     # thumbnails are at the top
                break
    return out
